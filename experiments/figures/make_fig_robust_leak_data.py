"""Data for the leakage figure (accuracy under three splitting protocols) and the background-robustness figure
(background swap, follow rate, cross-board transfer) of the leaf-blade experiments.

Inputs : results/runs/*.json
Outputs: figures/data/fig_leak.dat, figures/data/fig_robust.dat
"""
import json
from pathlib import Path
import pandas as pd

HERE = Path(__file__).resolve().parent
RUNS = HERE.parent / "results" / "runs"
OUT = HERE / "data"
OUT.mkdir(exist_ok=True)


def run(name):
    p = RUNS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def acc(name):
    r = run(name)
    return 100 * r["summary"]["acc"]["mean"] if r else float("nan")


# ------------------------------------------------------------------ leakage: random -> duplicate-grouped -> sequence-grouped
leak = [("Full image (ResNet50)", "leak_random_resnet50_full", None, "leak_group_resnet50_full"),
        ("Full image (DINOv2)", "proto_random_dinov2_s_deep_full", "proto_groupdup_dinov2_s_deep_full", "proto_group_dinov2_s_deep_full"),
        ("34-D global handcrafted", "leak_random_legacy34", None, "leak_group_legacy34"),
        ("164-D leaf handcrafted", "leak_random_hand164", None, "leak_group_hand164"),
        ("Leaf-blade encoder (DINOv2)", "proto_random_dinov2_s_proposed", "proto_groupdup_dinov2_s_proposed", "proto_group_dinov2_s_proposed")]
rows = []
for i, (lab, r, d, g) in enumerate(leak):
    rows.append({"id": i, "label": lab.replace(" ", "~"), "random": acc(r), "dup": acc(d) if d else float("nan"), "group": acc(g)})
pd.DataFrame(rows).to_csv(OUT / "fig_leak.dat", sep=" ", index=False, float_format="%.2f", na_rep="nan")
print(pd.DataFrame(rows).round(2).to_string(index=False))

# ------------------------------------------------------------------ robustness (top to bottom in the figure)
rob = [("Full image (ResNet50)", "resnet50", "deep_full", "cmp_resnet50_deep_full"),
       ("Full image (DINOv2)", "dinov2_s", "deep_full", "cmp_dinov2_s_deep_full"),
       ("34-D global handcrafted", "resnet50", "legacy34", "cmp_legacy34"),
       ("Leaf only (ResNet50)", "resnet50", "deep_leaf", "cmp_resnet50_deep_leaf"),
       ("Leaf only (DINOv2)", "dinov2_s", "deep_leaf", "cmp_dinov2_s_deep_leaf"),
       ("164-D leaf handcrafted", "resnet50", "hand164", "audit_hand164_leafonly"),
       ("Leaf-blade encoder (ResNet50)", "resnet50", "proposed", "cmp_resnet50_proposed"),
       ("Leaf-blade encoder (DINOv2)", "dinov2_s", "proposed", "cmp_dinov2_s_proposed")]
rows = []
n = len(rob)
for i, (lab, b, k, orig) in enumerate(rob):
    sw, xb = run(f"swap_{b}_{k}"), run(f"xboard_{b}_{k}")
    f = sorted(xb["folds"], key=lambda f: f["fold"])
    rows.append({"y": n - 1 - i, "label": lab, "orig": acc(orig), "swap": 100 * sw["swap_acc"],
                 "follow": 100 * sw["follow_rate"], "x_st_sq": 100 * f[0]["bal_acc"], "x_sq_st": 100 * f[1]["bal_acc"]})
d = pd.DataFrame(rows)
d.drop(columns="label").to_csv(OUT / "fig_robust.dat", sep=" ", index=False, float_format="%.2f")
print(d.round(2).to_string(index=False))

# ------------------------------------------------------------------ pgfplots commands for the leakage slope chart
styles = ["leakA", "leakD", "leakB", "leakC", "leakE"]  # same line style per representation as before
lines = []
for r, st in zip(pd.read_csv(OUT / "fig_leak.dat", sep=" ").itertuples(), styles):
    pts = [(0, r.random)] + ([(1, r.dup)] if pd.notna(r.dup) else []) + [(2, r.group)]
    coords = " ".join(f"({x},{y:.2f})" for x, y in pts)
    lines.append(rf"\addplot[{st}] coordinates {{{coords}}};" + "\n" + rf"\addlegendentry{{{r.label.replace('~', ' ')}}}")
(OUT / "fig_leak_plots.tex").write_text("% generated by make_fig_robust_leak_data.py\n" + "\n".join(lines) + "\n")
print((OUT / "fig_leak_plots.tex").read_text())
